    private void viewButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewButton1ActionPerformed
        // TODO add your handling code here:
        int selectedRow = dailyAppointmentsTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select an appointment from the table to view details.",
                    "No Selection",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            String timeStr = dailyAppointmentsTable.getValueAt(selectedRow, 0).toString();
            String patientName = dailyAppointmentsTable.getValueAt(selectedRow, 1).toString();

            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            String selectedDate = sdf.format(jDateChooser1.getDate());

            PatientDetailsDAO patientDetailsDAO = new PatientDetailsDAO();
            int patientUserId = patientDetailsDAO.getPatientIdByAppointmentDetails(
                    loggedInDentistId,
                    selectedDate,
                    timeStr,
                    patientName
            );

            if (patientUserId > 0) {
                PatientDetailsFrame detailsFrame = new PatientDetailsFrame(patientUserId);
                detailsFrame.setLocationRelativeTo(this);
                detailsFrame.setVisible(true);
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Patient record not found for the selected appointment.",
                        "Record Not Found",
                        JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error retrieving patient details: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_viewButton1ActionPerformed


