    public void loadDailySchedule() {
        if (jDateChooser1.getDate() == null) {
            return;
        }

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String selectedDate = sdf.format(jDateChooser1.getDate());

        DefaultTableModel model = (DefaultTableModel) dailyAppointmentsTable.getModel();
        model.setRowCount(0);

        List<Object[]> list = appointmentDAO.getDailyAppointmentsByDentistAndDate(loggedInDentistId, selectedDate);

        int totalCount = list.size();
        int completedCount = 0;
        int pendingCount = 0;

        for (Object[] row : list) {
            model.addRow(row);

            String status = row[4] != null ? row[4].toString() : "";
            if ("COMPLETED".equalsIgnoreCase(status)) {
                completedCount++;
            } else if ("SCHEDULED".equalsIgnoreCase(status) || "ACCEPTED".equalsIgnoreCase(status) || "PENDING".equalsIgnoreCase(status)) {
                pendingCount++;
            }
        }

        totalAppointmentLabel.setText(String.valueOf(totalCount));
        completeAppointmentLabel.setText(String.valueOf(completedCount));
        pendingLabel.setText(String.valueOf(pendingCount));
    }

