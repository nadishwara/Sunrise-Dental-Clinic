    public void setUser(User user) {
        this.currentUser = user;
        if (currentUser != null) {
            usernameUpdateTextField1.setText(currentUser.getUsername());
            contactNoUpdateTextField.setText(currentUser.getContactNo());
            whatsappNoUpdateTextField.setText(currentUser.getWhatsappNo());
            AddressUpdateTextField.setText(currentUser.getAddress());

            if (currentUser.getProfileImage() != null && !currentUser.getProfileImage().trim().isEmpty()) {
                try {
                    File imgFile = new File(currentUser.getProfileImage());
                    if (!imgFile.exists()) {
                        imgFile = new File(System.getProperty("user.dir"), currentUser.getProfileImage());
                    }

                    if (imgFile.exists()) {
                        ImageIcon icon = new ImageIcon(imgFile.getAbsolutePath());
                        int width = roundedProfileLabel.getWidth() > 0 ? roundedProfileLabel.getWidth() : 120;
                        int height = roundedProfileLabel.getHeight() > 0 ? roundedProfileLabel.getHeight() : 120;
                        
                        Image img = icon.getImage().getScaledInstance(width, height, Image.SCALE_SMOOTH);
                        roundedProfileLabel.setIcon(new ImageIcon(img));
                        roundedProfileLabel.revalidate();
                        roundedProfileLabel.repaint();
                        
                        selectedImagePath = currentUser.getProfileImage();
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }

