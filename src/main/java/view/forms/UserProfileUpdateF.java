    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        // TODO add your handling code here:
        if (currentUser == null) {
            return;
        }

        currentUser.setUsername(usernameUpdateTextField1.getText());
        currentUser.setContactNo(contactNoUpdateTextField.getText());
        currentUser.setWhatsappNo(whatsappNoUpdateTextField.getText());
        currentUser.setAddress(AddressUpdateTextField.getText());

        if (selectedImagePath != null && !selectedImagePath.equals(currentUser.getProfileImage())) {
            try {
                File sourceFile = new File(selectedImagePath);
                File projectDir = new File(System.getProperty("user.dir"), "uploads" + File.separator + "profiles");
                if (!projectDir.exists()) {
                    projectDir.mkdirs();
                }

                String fileName = "user_" + currentUser.getUserId() + "_" + System.currentTimeMillis() + "_" + sourceFile.getName();
                File destFile = new File(projectDir, fileName);

                Files.copy(sourceFile.toPath(), destFile.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING);

                String relativePath = "uploads" + File.separator + "profiles" + File.separator + fileName;
                currentUser.setProfileImage(relativePath);

            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Failed to copy image file: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        UserDAO userDao = new UserDAO();
        boolean success = userDao.updateUserProfile(currentUser);

        if (success) {
            JOptionPane.showMessageDialog(this, "Profile updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

            if (parentPanel != null) {
                parentPanel.setUserData(currentUser);
            }

            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update profile.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_updateButtonActionPerformed

    private void profileImageChooseButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_profileImageChooseButtonActionPerformed
        // TODO add your handling code here:
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setFileFilter(new FileNameExtensionFilter("Images", "jpg", "png", "jpeg", "gif"));

        int result = fileChooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File selectedFile = fileChooser.getSelectedFile();
            selectedImagePath = selectedFile.getAbsolutePath();

            ImageIcon icon = new ImageIcon(selectedImagePath);
            int width = roundedProfileLabel.getWidth() > 0 ? roundedProfileLabel.getWidth() : 120;
            int height = roundedProfileLabel.getHeight() > 0 ? roundedProfileLabel.getHeight() : 120;
            
            Image img = icon.getImage().getScaledInstance(width, height, Image.SCALE_SMOOTH);
            roundedProfileLabel.setIcon(new ImageIcon(img));
            roundedProfileLabel.revalidate();
            roundedProfileLabel.repaint();
        }
    }//GEN-LAST:event_profileImageChooseButtonActionPerformed

